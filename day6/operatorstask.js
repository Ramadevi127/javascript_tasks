let n1=10
let n2=20
let opr='*'
switch(opr){
    case '+':
        console.log(n1+n2);
        break
    case '-':
        console.log(n1-n2);
        break 
    case '*':
        console.log(n1*n2);
        break
    case '/':
        console.log(n1/n2);
        break
    default:
        console.log("invalid operator");
        
}
